package com.mytri.genshin_calculator;

public class CharacterSkillIds {
    private String normalAttack;
    private String skill;
    private String burst;

    public String getNormalAttack() {
        return normalAttack;
    }
    public void setNormalAttack(String normalAttack) {
        this.normalAttack = normalAttack;
    }
    public String getSkill() {
        return skill;
    }
    public void setSkill(String skill) {
        this.skill = skill;
    }
    public String getBurst() {
        return burst;
    }
    public void setBurst(String burst) {
        this.burst = burst;
    }
}
